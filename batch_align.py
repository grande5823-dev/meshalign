#!/usr/bin/env python3
import argparse
import subprocess
import shutil
import sys
from pathlib import Path
import pandas as pd
import meshalign as ma

def main() -> None:
    ap = argparse.ArgumentParser(description="Batch process test meshes, run DFT alignment, and consolidate individual surf_mae and surf_dft CSVs.")
    ap.add_argument("--ref", type=Path, required=True, help="Path to the reference mesh (STL)")
    ap.add_argument("--test-dir", type=Path, required=True, help="Directory containing the test STL files")
    ap.add_argument("--out-dir", type=Path, default=Path("batch_dft_results"), help="Output root directory for results")
    ap.add_argument("--no-icp", action="store_true", help="Disable ICP registration")
    ap.add_argument("--clear-out", action="store_true", help="Clear the output directory before starting batch processing")
    
    args = ap.parse_args()

    # Handle clearing out-dir for tidiness
    if args.out_dir.exists():
        if args.clear_out:
            print(f"Clearing existing output directory: {args.out_dir}")
            shutil.rmtree(args.out_dir)
        else:
            print(f"Output directory {args.out_dir} already exists. New files will be merged/added.")

    args.out_dir.mkdir(parents=True, exist_ok=True)

    test_files = list(args.test_dir.glob("*.stl"))
    if not test_files:
        print(f"Error: No STL files found in {args.test_dir}")
        sys.exit(1)

    print(f"Found {len(test_files)} test STLs. Starting batch DFT processing...")
    
    # Execute alignment and measurement for each test STL
    for i, test_path in enumerate(test_files, 1):
        print(f"\n[{i}/{len(test_files)}] Processing: {test_path.name}")
        
        # Create a dedicated output subdirectory for each pair's artifacts
        pair_out_dir = args.out_dir / test_path.stem
        pair_out_dir.mkdir(parents=True, exist_ok=True)

        try:
            mae_um, p95_um, char_um, rel_mae, rel_p95 = ma.run_pair_relative(
                str(args.ref), str(test_path), str(pair_out_dir), 
                use_icp=not args.no_icp, histogram=True,
                save_per_sample=False
            )
            print(f"  -> Success: MAE = {mae_um:.1f} um, Rel DFT = {rel_mae:.3f}%")
        except Exception as e:
            print(f"  -> Warning: Processing failed for {test_path.name}. Error: {e}")

    # Consolidate individual CSV outputs generated by meshalign
    print("\nConsolidating individual result CSVs...")

    # 1. Consolidate surf_mae files
    mae_csvs = [p for p in args.out_dir.rglob("*.csv") if "surf_mae" in p.name]

    if mae_csvs:
        mae_dfs = []
        for csv_path in mae_csvs:
            test_name = csv_path.parent.name if csv_path.parent != args.out_dir else csv_path.stem
            df = pd.read_csv(csv_path)
            # Insert indicator columns at the very front
            df.insert(0, "test_mesh", test_name)
            df.insert(1, "reference_mesh", args.ref.name)
            mae_dfs.append(df)
            
        consolidated_mae = pd.concat(mae_dfs, ignore_index=True)
        out_mae_csv = args.out_dir / "consolidated_surf_mae.csv"
        
        consolidated_mae.to_csv(out_mae_csv, index=False)
        print(f"Saved consolidated surf_mae to:\n - {out_mae_csv}")
    else:
        print("No 'surf_mae' CSV files found to consolidate.")

    # 2. Consolidate surf_dft files
    dft_csvs = [p for p in args.out_dir.rglob("*.csv") if "surf_dft" in p.name]

    if dft_csvs:
        dft_dfs = []
        for csv_path in dft_csvs:
            test_name = csv_path.parent.name if csv_path.parent != args.out_dir else csv_path.stem
            df = pd.read_csv(csv_path)
            # Insert indicator columns at the front
            df.insert(0, "test_mesh", test_name)
            df.insert(1, "reference_mesh", args.ref.name)
            dft_dfs.append(df)
            
        consolidated_dft = pd.concat(dft_dfs, ignore_index=True)
        out_dft_csv = args.out_dir / "consolidated_surf_dft.csv"
        
        consolidated_dft.to_csv(out_dft_csv, index=False)
        print(f"Saved consolidated surf_dft to:\n - {out_dft_csv}")
    else:
        print("No 'surf_dft' CSV files found to consolidate.")

    print("\nBatch processing and consolidation complete!")

if __name__ == "__main__":
    main()